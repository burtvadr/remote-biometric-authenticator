#!/usr/bin/env python3
"""Generate synthetic, non-production attestation fixtures and check PKIX paths.
Requires Python cryptography and OpenSSL CLI. Test keys are public constants;
never configure these roots in an installation. ECDSA certificates use randomized
signatures; generated bytes need not match the checked-in fixture byte-for-byte.
"""
import argparse
import datetime as dt
from pathlib import Path
import subprocess
import tempfile
from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.x509.oid import NameOID, ObjectIdentifier

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'linux/rbad/src/v2_store/attestation/fixtures/chains.tsv'
OID = ObjectIdentifier('1.3.6.1.4.1.11129.2.1.17')
NOW = dt.datetime(2026, 1, 1, tzinfo=dt.timezone.utc)
CHALLENGE = bytes([0x33])*32
SIGNER = bytes([0x44])*32
PACKAGE = b'io.github.burtvadr.rba'

def der(tag, data, cls=0, cons=False):
    if tag < 31:
        h = bytes([(cls<<6)|(0x20 if cons else 0)|tag])
    else:
        parts = [tag&127]
        tag >>= 7
        while tag:
            parts.append(0x80|(tag&127)); tag >>= 7
        h = bytes([(cls<<6)|(0x20 if cons else 0)|31]+parts[::-1])
    n = len(data)
    length = bytes([n]) if n<128 else n.to_bytes((n.bit_length()+7)//8,'big')
    if n>=128: length = bytes([128+len(length)])+length
    return h+length+data

def num(n, tag=2):
    b = n.to_bytes(max(1,(n.bit_length()+7)//8),'big')
    return der(tag, (b'\0' if b[0]&128 else b'')+b)

def seq(*xs): return der(16,b''.join(xs),cons=True)
def setof(*xs): return der(17,b''.join(sorted(xs)),cons=True)
def octet(b): return der(4,b)
def null(): return der(5,b'')
def explicit(tag,value): return der(tag,value,cls=2,cons=True)

def description(biometric, change=None):
    sw = {701:num(int(NOW.timestamp())*1000),709:octet(seq(setof(seq(octet(PACKAGE),num(10))),setof(octet(SIGNER))))}
    hw = {1:setof(num(2)),2:num(3),3:num(256),5:setof(num(4)),10:num(1),702:num(0),704:seq(octet(b'K'*32),der(1,b'\xff'),num(0,10),octet(b'H'*32)),705:num(140000),706:num(202512),718:num(20251205),719:num(20251205)}
    hw[504 if biometric else 503] = num(2) if biometric else null()
    if not biometric: hw[5]=setof(num(0),num(4))
    if change=='transport_sha_only': hw[5]=setof(num(4))
    if change=='transport_none_only': hw[5]=setof(num(0))
    if change=='bio_none': hw[5]=setof(num(0),num(4))
    level, km_level, challenge = 1,1,CHALLENGE
    if change=='software': level=0
    if change=='software_key': km_level=0
    if change=='wrong_challenge': challenge=b'X'*32
    if change=='wrong_app': sw[709]=octet(seq(setof(seq(octet(b'io.github.burtvadr.rba.debug'),num(10))),setof(octet(SIGNER))))
    if change=='wrong_signer': sw[709]=octet(seq(setof(seq(octet(PACKAGE),num(10))),setof(octet(b'X'*32))))
    if change=='old_app': sw[709]=octet(seq(setof(seq(octet(PACKAGE),num(1))),setof(octet(SIGNER))))
    if change=='unlocked': hw[704]=seq(octet(b'K'*32),der(1,b'\0'),num(0,10),octet(b'H'*32))
    if change=='unverified_boot': hw[704]=seq(octet(b'K'*32),der(1,b'\xff'),num(2,10),octet(b'H'*32))
    if change=='stale_patch': hw[706]=num(202401)
    if change=='missing_vendor': del hw[718]
    if change=='timeout': hw[505]=num(30)
    if change=='password': hw[504]=num(3)
    if change=='software_auth': sw[504]=hw.pop(504)
    if change=='wrong_purpose': hw[1]=setof(num(2),num(3))
    if change=='imported': hw[702]=num(2)
    if change=='both_auth': hw[503]=null()
    if change=='duplicate_tag': sw[3]=hw[3]
    if change=='unknown_tag': hw[999]=null()
    hw_seq=[explicit(k,v) for k,v in sorted(hw.items())]
    if change=='duplicate_hw': hw_seq.append(explicit(719,num(20251205)))
    data=seq(num(300),num(level,10),num(300),num(km_level,10),octet(challenge),octet(b''),seq(*(explicit(k,v) for k,v in sorted(sw.items()))),seq(*hw_seq))
    if change=='trailing': data+=b'\0'
    return data

def key(n): return ec.derive_private_key(n,ec.SECP256R1())
def cert(subject,key,issuer,issuer_key,serial,ca=False,ext=None,expired=False):
    start=NOW-dt.timedelta(days=730)
    end=NOW+dt.timedelta(days=-1 if expired else 730)
    b=x509.CertificateBuilder().subject_name(subject).issuer_name(issuer).public_key(key.public_key()).serial_number(serial).not_valid_before(start).not_valid_after(end)
    b=b.add_extension(x509.BasicConstraints(ca=ca,path_length=1 if ca else None),True)
    b=b.add_extension(x509.KeyUsage(digital_signature=not ca,content_commitment=False,key_encipherment=False,data_encipherment=False,key_agreement=False,key_cert_sign=ca,crl_sign=ca,encipher_only=False,decipher_only=False),True)
    b=b.add_extension(x509.SubjectKeyIdentifier.from_public_key(key.public_key()),False)
    b=b.add_extension(x509.AuthorityKeyIdentifier.from_issuer_public_key(issuer_key.public_key()),False)
    if ext is not None: b=b.add_extension(x509.UnrecognizedExtension(OID,ext),False)
    return b.sign(issuer_key,hashes.SHA256())

def name(s): return x509.Name([x509.NameAttribute(NameOID.COMMON_NAME,s)])
def encoded(c): return c.public_bytes(serialization.Encoding.DER).hex()
def point(k): return k.public_key().public_bytes(serialization.Encoding.X962,serialization.PublicFormat.UncompressedPoint).hex()

def generate():
    root,inter,bio,trans=map(key,(101,102,103,104))
    rn,inn,ln=map(name,('RBA TEST ONLY root','RBA TEST ONLY intermediate','RBA TEST ONLY leaf'))
    roots=cert(rn,root,rn,root,1,True)
    intermediate=cert(inn,inter,rn,root,2,True)
    bad_inter=cert(inn,inter,rn,root,3,True,description(True))
    rows={'root':encoded(roots),'intermediate':encoded(intermediate),'intermediate_extension':encoded(bad_inter),'bio_key':point(bio),'transport_key':point(trans)}
    changes=['software','software_key','wrong_challenge','wrong_app','wrong_signer','old_app','unlocked','unverified_boot','stale_patch','missing_vendor','timeout','password','software_auth','wrong_purpose','imported','both_auth','duplicate_tag','unknown_tag','duplicate_hw','trailing']
    for idx,change in enumerate(['biometric','transport','transport_sha_only','transport_none_only','bio_none','expired','missing_extension']+changes,10):
        role=change not in ('transport','transport_sha_only','transport_none_only'); k=bio if role else trans
        ext=None if change=='missing_extension' else description(role,change)
        rows[change]=encoded(cert(ln,k,inn,inter,idx,ext=ext,expired=change=='expired'))
    OUT.write_text('# Synthetic test fixtures; never trust these roots in production.\n'+''.join(f'{k}\t{v}\n' for k,v in rows.items()))

def check():
    rows=dict(l.split('\t') for l in OUT.read_text().splitlines() if l and not l.startswith('#'))
    count=0
    with tempfile.TemporaryDirectory() as tmp:
        p=Path(tmp)
        for k,v in rows.items():
            if k.endswith('_key'): continue
            cert=x509.load_der_x509_certificate(bytes.fromhex(v))
            (p/(k+'.pem')).write_bytes(cert.public_bytes(serialization.Encoding.PEM))
        for leaf in rows:
            if leaf.endswith('_key') or leaf in ('root','intermediate','intermediate_extension'): continue
            cmd=['openssl','verify','-x509_strict','-check_ss_sig','-auth_level','2','-attime',str(int(NOW.timestamp())),'-CAfile',str(p/'root.pem'),'-untrusted',str(p/'intermediate.pem'),str(p/(leaf+'.pem'))]
            result=subprocess.run(cmd,capture_output=True,text=True)
            assert (result.returncode==0)==(leaf!='expired'), (leaf,result.stdout,result.stderr)
            count+=1
        # Do not trust an intermediate supplied as a root by the remote peer.
        result=subprocess.run(['openssl','verify','-x509_strict','-attime',str(int(NOW.timestamp())),'-CAfile',str(p/'intermediate.pem'),str(p/'biometric.pem')],capture_output=True,text=True)
        assert result.returncode!=0
        count+=1
    print(f'PASS: {count} independent OpenSSL certificate-path fixture checks (not Android policy execution)')

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--generate',action='store_true');a=p.parse_args()
    if a.generate: generate()
    check()
