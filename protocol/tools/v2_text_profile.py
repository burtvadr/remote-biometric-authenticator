#!/usr/bin/env python3
"""Render the pinned repertoire into both implementations; no runtime data downloads."""
from pathlib import Path
import argparse
ROOT=Path(__file__).resolve().parents[2]
TABLE=ROOT/'protocol/text-profile/rba-display-text-1.tsv'

def ranges():
    out=[]
    for line in TABLE.read_text().splitlines():
        if line.startswith('#'): continue
        lo,hi=map(lambda s:int(s,16),line.split('\t'))
        assert 0<=lo<=hi<=0x10ffff and (not out or out[-1][1]+1<lo)
        out.append((lo,hi))
    return out

def render():
    pairs=ranges()
    assert pairs and len(pairs)<1000
    rust='''// Generated by protocol/tools/v2_text_profile.py; do not edit.
// Normative repertoire: protocol/text-profile/rba-display-text-1.tsv.
use unicode_normalization::is_nfc;
const RANGES: &[(u32,u32)] = &[\n'''
    rust+=''.join(f'    (0x{lo:x}, 0x{hi:x}),\n' for lo,hi in pairs)
    rust+=''' ];
fn allowed(c: char) -> bool {
    let n = c as u32;
    let i = RANGES.partition_point(|&(_, hi)| hi < n);
    RANGES.get(i).is_some_and(|&(lo, _)| lo <= n)
}
pub(crate) fn label(s: &str, max: usize) -> bool {
    !s.is_empty() && s.len() <= max && s.chars().all(allowed) && is_nfc(s)
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn exact_repertoire_and_boundaries() {
        let mut expected = vec![false; 0x110000];
        for line in include_str!("../../../protocol/text-profile/rba-display-text-1.tsv").lines().filter(|l| !l.starts_with('#')) {
            let (lo, hi) = line.split_once('\\t').unwrap();
            let lo = usize::from_str_radix(lo, 16).unwrap();
            let hi = usize::from_str_radix(hi, 16).unwrap();
            expected[lo..=hi].fill(true);
        }
        for n in 0..=0x10ffff {
            if let Some(c) = char::from_u32(n) { assert_eq!(allowed(c), expected[n as usize], "U+{n:04X}"); }
        }
    }
}
'''
    kt='''// Generated by protocol/tools/v2_text_profile.py; do not edit.
// Normative repertoire: protocol/text-profile/rba-display-text-1.tsv.
package io.github.burtvadr.rba.protocol

import java.text.Normalizer

internal object V2TextProfile {
    private val ranges = intArrayOf(\n'''
    kt+=''.join(f'        0x{lo:x}, 0x{hi:x},\n' for lo,hi in pairs)
    kt+='''    )
    internal fun allowed(cp: Int): Boolean {
        var lo = 0
        var hi = ranges.size / 2
        while (lo < hi) {
            val mid = (lo + hi) / 2
            if (ranges[mid * 2 + 1] < cp) lo = mid + 1 else hi = mid
        }
        return lo < ranges.size / 2 && ranges[lo * 2] <= cp
    }
    fun label(s: String, max: Int): Boolean {
        if (s.length !in 1..max || s.toByteArray(Charsets.UTF_8).size !in 1..max) return false
        var i = 0
        while (i < s.length) {
            val cp = s.codePointAt(i)
            if (!allowed(cp)) return false
            i += Character.charCount(cp)
        }
        return Normalizer.isNormalized(s, Normalizer.Form.NFC)
    }
}
'''
    return {ROOT/'linux/protocol/src/v2_text_profile.rs':rust,ROOT/'android/protocol/src/main/kotlin/io/github/burtvadr/rba/protocol/V2TextProfile.kt':kt}

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    for path,data in render().items():
        if a.check:
            if path.read_text()!=data: raise SystemExit(f'drift: {path}')
        else: path.write_text(data)
    print(f'RBA Display Text 1: {len(ranges())} ranges verified')
if __name__=='__main__': main()
