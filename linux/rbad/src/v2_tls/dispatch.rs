//! Connection-owning V2 operation drivers. Only a trusted local adapter may
//! create a LocalLink or select an admitted request. No remote request routes
//! to a local authentication or enrollment, and no IPC claim is trusted here.
//! The drivers consume their Channel and never expose an authentication token.
use super::*;
use crate::v2_store::authority::{EnrollmentApproval, EntryDirection};
use crate::v2_store::{Grant,Principal};
use p256::ecdsa::SigningKey;
use rba_enrollment::PairingCode;
use std::future::Future;
use tokio::sync::{mpsc, oneshot};
use zeroize::Zeroizing;

pub(crate) mod scheduler;
pub(crate) mod routes;

type Deadline = tokio::time::Instant;

/// Dedicated mailbox for one locally verified interaction. The receiver must
/// belong exclusively to the original live IPC owner (B.4), and be dropped on
/// its disconnection. A display acknowledgement is sent only after delivery
/// to that interaction, not simply after placing the event in a queue.
/// Secret fields deliberately have no Debug implementation.
pub(crate) enum LocalEvent {
    DisplayNumber { digits: Zeroizing<[u8; 6]>, shown: oneshot::Sender<()> },
    DisplayPairingCode { digits: Zeroizing<[u8; 6]>, shown: oneshot::Sender<()> },
    EnterPairingCode { reply: oneshot::Sender<Zeroizing<[u8; 6]>> },
    ReviewEnrollment { facts: EnrollmentApproval, reply: oneshot::Sender<Approval> },
    Authenticated { interaction: Id, expires_wall: i64, expires_mono: Instant },
    EnrollmentCommitted { enrollment: Id },
}

pub(crate) struct Approval {
    pub context_hash: Hash,
    pub replacements: Vec<Id>,
    pub initial_cli: bool,
}

pub(crate) struct LocalLink {
    owner: Id,
    interaction: Id,
    tx: mpsc::Sender<LocalEvent>,
}

impl LocalLink {
    /// IDs are generated by the verified local adapter, never deserialized
    /// from either local request content or remote protocol messages.
    pub(crate) fn new(owner: Id, interaction: Id) -> Result<(Self, mpsc::Receiver<LocalEvent>)> {
        if owner == [0; 16] || interaction == [0; 16] { return Err(Error::Denied); }
        let (tx, rx) = mpsc::channel(1);
        Ok((Self { owner, interaction, tx }, rx))
    }

    fn live(&self, deadline: Deadline) -> Result<()> {
        if self.tx.is_closed() || Deadline::now() >= deadline { return Err(Error::Denied); }
        Ok(())
    }

    async fn wait<T>(&self, deadline: Deadline, work: impl Future<Output = Result<T>>) -> Result<T> {
        self.live(deadline)?;
        let result = tokio::select! {
            biased;
            _ = self.tx.closed() => Err(Error::Denied),
            out = timeout_at(deadline, work) => out.map_err(|_| Error::Clock)?,
        }?;
        self.live(deadline)?;
        Ok(result)
    }

    async fn ask<T>(&self, deadline: Deadline, make: impl FnOnce(oneshot::Sender<T>) -> LocalEvent) -> Result<T> {
        let (reply, answer) = oneshot::channel();
        self.wait(deadline, async {
            self.tx.send(make(reply)).await.map_err(|_| Error::Denied)?;
            answer.await.map_err(|_| Error::Denied)
        }).await
    }

    /// Nonblocking delivery while the authority lock still serializes the
    /// verified completion. This is an internal event, not a bearer token.
    fn complete(&self, deadline: Deadline, event: LocalEvent) -> Result<()> {
        self.live(deadline)?;
        self.tx.try_send(event).map_err(|_| Error::Denied)
    }
}

struct LocalGuard { authority: Owner, owner: Id }
impl Drop for LocalGuard {
    fn drop(&mut self) {
        if let Ok(mut a) = self.authority.lock() { a.close_local(self.owner); }
    }
}

fn clock() -> Result<(i64, Instant)> { Ok((wall()?, Instant::now())) }
fn locked<T>(owner: &Owner, f: impl FnOnce(&mut Authority) -> Result<T>) -> Result<T> {
    let mut a = owner.lock().map_err(|_| Error::State)?;
    f(&mut a)
}

/// Delivery status only: local authentication success can be sent exclusively
/// via the dedicated LocalEvent::Authenticated mailbox. Loss of the remote
/// receipt does not roll back the already committed authority decision.
#[derive(Debug, PartialEq, Eq)]
pub(crate) enum ReceiptDelivery { Sent, NotConfirmed }

async fn finish(channel: Channel, local: &LocalLink, deadline: Deadline) -> ReceiptDelivery {
    if local.wait(deadline, channel.finish()).await.is_ok() { ReceiptDelivery::Sent }
    else { ReceiptDelivery::NotConfirmed }
}

async fn read_auth(channel: &mut Channel, local: &LocalLink, deadline: Deadline, expected: Kind) -> Result<Message> {
    let msg = local.wait(deadline, channel.read_until(deadline)).await?;
    if msg.kind() == Kind::Cancel {
        let (now, mono) = clock()?;
        locked(&channel.stream.get_ref().0.owner, |a| a.auth_cancel(channel.id(), &msg, now, mono))?;
        return Err(Error::Denied);
    }
    if msg.kind() != expected { return Err(Error::Denied); }
    Ok(msg)
}

async fn read_enrollment(channel: &mut Channel, local: &LocalLink, deadline: Deadline, expected: Kind) -> Result<Message> {
    let msg = local.wait(deadline, channel.read_until(deadline)).await?;
    if msg.kind() == Kind::EnrollCancel {
        let (now, mono) = clock()?;
        locked(&channel.stream.get_ref().0.owner, |a| a.enrollment_cancel(channel.id(), &msg, now, mono))?;
        return Err(Error::Denied);
    }
    if msg.kind() != expected { return Err(Error::Denied); }
    Ok(msg)
}

impl Channel {
    /// Route one already-admitted authentication. Source/detail come from the
    /// verified adapter; the signer must be the actual TLS host identity.
    pub(crate) async fn authenticate(mut self, local: LocalLink, request: Id, signer: &SigningKey, source: &str, detail: &str) -> Result<ReceiptDelivery> {
        if self.mode != Listener::Production || self.access != Some(PeerState::Active) || self.purpose()!=Some(Purpose::Authentication)
            || signer.verifying_key().to_encoded_point(false).as_bytes() != self.binding.host_key.as_slice() {
            return Err(Error::Denied);
        }
        let owner = self.stream.get_ref().0.owner.clone();
        let conn = self.id();
        let (expires_wall, deadline, dispatch) = locked(&owner, |a| {
            let (expires_wall, expires_mono) = a.auth_route(local.owner, local.interaction, request, conn)?;
            let deadline = Deadline::from_std(expires_mono);
            let result = (|| {
                local.live(deadline)?;
                let (now, mono) = clock()?;
                a.start_auth(local.owner, request, conn, signer, source, detail, now, mono)
            })();
            if result.is_err() { a.cancel_local(local.owner, request); }
            Ok((expires_wall, deadline, result?))
        })?;
        // Routing and start share one lock: a second route cannot install a
        // cancellation guard for an already-dispatched interaction.
        let _guard = LocalGuard { authority: owner.clone(), owner: local.owner };
        local.ask(deadline, |shown| LocalEvent::DisplayNumber { digits: dispatch.number, shown }).await?;
        local.wait(deadline, self.write(&dispatch.message)).await?;
        let entry = read_auth(&mut self, &local, deadline, Kind::NumberEntry).await?;
        let (now, mono) = clock()?;
        let matched = locked(&owner, |a| a.auth_number(conn, &entry, signer, now, mono))?;
        local.wait(deadline, self.write(&matched)).await?;
        let response = read_auth(&mut self, &local, deadline, Kind::AuthResponse).await?;
        locked(&owner, |a| {
            local.live(deadline)?;
            let accepted = a.auth_response(conn, &response, clock)?;
            if accepted.owner != local.owner || accepted.interaction != local.interaction { return Err(Error::Denied); }
            if wall()? >= expires_wall { return Err(Error::Clock); }
            local.complete(deadline, LocalEvent::Authenticated { interaction: accepted.interaction, expires_wall, expires_mono: deadline.into_std() })
        })?;
        Ok(finish(self, &local, deadline).await)
    }

    /// The trusted local adapter selects the exact credential, principal,
    /// revision and desired grants. No remote policy request is routed here.
    pub(crate) async fn synchronize_policy(mut self, local:LocalLink, credential:Id, caller:Principal, expected:i64, grants:&[Grant], local_deadline:Deadline)->Result<(bool,ReceiptDelivery)> {
        if self.mode!=Listener::Production || self.access!=Some(PeerState::Active) || self.purpose()!=Some(Purpose::Policy) || self.credential()!=Some(credential) {return Err(Error::Denied)}
        let owner=self.stream.get_ref().0.owner.clone(); let conn=self.id();
        let (message,deadline)=locked(&owner,|a|{
            let (now,mono)=clock()?;
            local.live(local_deadline)?;
            a.policy_offer_until(conn,local.owner,caller,expected,grants,now,mono,local_deadline.into_std())
        })?;
        let deadline=Deadline::from_std(deadline);
        let _guard=LocalGuard{authority:owner.clone(),owner:local.owner};
        local.wait(deadline,self.write(&message)).await?;
        let decision=local.wait(deadline,self.read_until(deadline)).await?;
        let accepted=locked(&owner,|a|{local.live(deadline)?;let(now,mono)=clock()?;a.policy_decision(conn,local.owner,&decision,now,mono)})?;
        if accepted {Ok((true,finish(self,&local,deadline).await))}else{Ok((false,ReceiptDelivery::NotConfirmed))}
    }

    /// Route one explicit local pairing, using TLS-derived facts and an exact
    /// locally acknowledged fingerprint/context approval. No callback is
    /// awaited while holding the shared authority lock.
    pub(crate) async fn enroll(mut self, local: LocalLink, enrollment: Id, direction: EntryDirection) -> Result<ReceiptDelivery> {
        let binding = self.enrollment_binding()?;
        let owner = self.stream.get_ref().0.owner.clone();
        let conn = self.id();
        let (deadline, start) = locked(&owner, |a| {
            let deadline = Deadline::from_std(a.pairing_route(local.owner, enrollment, conn)?);
            let result = (|| {
                local.live(deadline)?;
                let (now, mono) = clock()?;
                a.enrollment_start(local.owner, conn, direction, binding, now, mono)
            })();
            if result.is_err() { a.cancel_pairing_local(local.owner, enrollment); }
            Ok((deadline, result?))
        })?;
        let _guard = LocalGuard { authority: owner.clone(), owner: local.owner };
        if let Some(digits) = start.display_code {
            local.ask(deadline, |shown| LocalEvent::DisplayPairingCode { digits, shown }).await?;
        }
        local.wait(deadline, self.write(&start.message)).await?;
        let share = read_enrollment(&mut self, &local, deadline, Kind::EnrollShare).await?;
        let entered = if direction == EntryDirection::HostTypes {
            let digits = local.ask(deadline, |reply| LocalEvent::EnterPairingCode { reply }).await?;
            Some(PairingCode::parse(digits.as_slice()).map_err(|_| Error::Denied)?)
        } else { None };
        let (now, mono) = clock()?;
        let confirmation = locked(&owner, |a| a.enrollment_share(local.owner, conn, &share, entered, now, mono))?;
        local.wait(deadline, self.write(&confirmation)).await?;
        let confirm = read_enrollment(&mut self, &local, deadline, Kind::EnrollConfirmB).await?;
        let (now, mono) = clock()?;
        locked(&owner, |a| a.enrollment_confirm(conn, &confirm, now, mono))?;
        let evidence = read_enrollment(&mut self, &local, deadline, Kind::EnrollEvidence).await?;
        let facts = locked(&owner, |a| a.enrollment_evidence(conn, &evidence, clock))?;
        if facts.enrollment != enrollment { return Err(Error::Denied); }
        let approval = local.ask(deadline, |reply| LocalEvent::ReviewEnrollment { facts, reply }).await?;
        let (now, mono) = clock()?;
        let offer = locked(&owner, |a| a.enrollment_approve(local.owner, conn, approval.context_hash, &approval.replacements, approval.initial_cli, now, mono))?;
        local.wait(deadline, self.write(&offer)).await?;
        let staged = read_enrollment(&mut self, &local, deadline, Kind::EnrollStaged).await?;
        locked(&owner, |a| {
            local.live(deadline)?;
            a.enrollment_staged(conn, &staged, clock)?;
            local.complete(deadline, LocalEvent::EnrollmentCommitted { enrollment })
        })?;
        Ok(finish(self, &local, deadline).await)
    }

    /// Device-initiated recovery/revocation is never routed to a local
    /// authentication. The authority restricts revocation-only credentials and
    /// validates exact session, credential and token before arming a receipt.
    pub(crate) async fn peer_terminal(mut self) -> Result<()> {
        if self.mode != Listener::Production || self.access.is_none() || !matches!(self.purpose(),Some(Purpose::Recovery|Purpose::Revocation)) { return Err(Error::Denied); }
        let owner = self.stream.get_ref().0.owner.clone();
        let conn = self.id();
        let msg = self.read_until(Deadline::now() + FRAME_TIME).await?;
        let (now, mono) = clock()?;
        locked(&owner, |a| match msg.kind() {
            Kind::Revoke => a.revoke_peer(conn, &msg, now, mono),
            Kind::EnrollStatus => a.enrollment_status(conn, &msg, now, mono).map(|_| ()),
            _ => Err(Error::Denied),
        })?;
        self.finish().await
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[tokio::test]
    async fn local_display_requires_ack_and_rejects_disconnect() {
        let (local, mut rx) = LocalLink::new([1; 16], [2; 16]).unwrap();
        let deadline = Deadline::now() + Duration::from_secs(2);
        let task = local.ask(deadline, |shown| LocalEvent::DisplayNumber { digits: Zeroizing::new(*b"012345"), shown });
        let client = async {
            match rx.recv().await.unwrap() {
                LocalEvent::DisplayNumber { digits, shown } => { assert_eq!(*digits, *b"012345"); drop(shown); }
                _ => panic!("wrong event"),
            }
        };
        let (result, _) = tokio::join!(task, client);
        assert!(result.is_err());
        drop(rx);
        assert!(local.complete(deadline, LocalEvent::Authenticated { interaction: [2; 16], expires_wall: wall().unwrap()+1, expires_mono: deadline.into_std() }).is_err());
    }
    #[tokio::test]
    async fn local_display_uses_original_deadline() {
        let (local, _rx) = LocalLink::new([1; 16], [2; 16]).unwrap();
        let deadline = Deadline::now() + Duration::from_millis(20);
        let r = local.ask(deadline, |shown| LocalEvent::DisplayNumber { digits: Zeroizing::new(*b"012345"), shown }).await;
        assert!(r.is_err());
        assert!(local.complete(deadline, LocalEvent::Authenticated { interaction: [2; 16], expires_wall: wall().unwrap()+1, expires_mono: deadline.into_std() }).is_err());
    }
    #[tokio::test]
    async fn local_acknowledgement_then_exact_completion() {
        let (local, mut rx) = LocalLink::new([1; 16], [2; 16]).unwrap();
        let deadline = Deadline::now() + Duration::from_secs(2);
        let task = async {
            local.ask(deadline, |shown| LocalEvent::DisplayNumber { digits: Zeroizing::new(*b"012345"), shown }).await.unwrap();
            local.complete(deadline, LocalEvent::Authenticated { interaction: [2; 16], expires_wall: wall().unwrap()+1, expires_mono: deadline.into_std() }).unwrap();
        };
        let client = async {
            if let LocalEvent::DisplayNumber { shown, .. } = rx.recv().await.unwrap() { shown.send(()).unwrap(); } else { panic!("wrong event"); }
            match rx.recv().await.unwrap() { LocalEvent::Authenticated { interaction, .. } => assert_eq!(interaction, [2; 16]), _ => panic!("wrong event") }
        };
        tokio::join!(task, client);
    }
}
